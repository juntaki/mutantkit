#!/usr/bin/env python3
"""Sync .public-tree.toml's `forbidden_strings` array from
Scripts/local-project-names.txt.

Why this exists: git-projector's `forbidden_strings` policy field is a
plain inline TOML array of regex strings (see
~/work/git-projector/src/git_projector/config.py -- `_compile_all(policy
.get("forbidden_strings", []), ...)`); it has no mechanism to read an
external file at scan time. So Scripts/local-project-names.txt (the
maintained, `ls ~/work`-derived list of every real local project name) is
folded into the TOML array by *this* script instead, run by hand after
editing the .txt file, rather than read live by the scan itself. Run this,
then `Scripts/preflight.sh`, before publishing.

What it does NOT touch: the three pre-existing "floor" entries
(`(?i)Yomu`, `(?i)InfiniteNote`, `(?i)m1mac`) covered by
PublicTreeConfigRegressionTests's own `floorEntriesArePresent` test, or any
other forbidden_strings entry not generated by this script -- it only adds
missing, name-derived entries after them. It never removes or reorders an
existing line, and running it twice in a row is a no-op the second time.

Usage:
    Scripts/sync-local-project-name-forbidden-strings.py [--check]

    --check   exit 1 if .public-tree.toml is NOT already in sync (used by
              PublicTreeConfigRegressionTests's own drift check, and safe
              to run in CI); makes no changes either way.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
NAMES_FILE = REPO_ROOT / "Scripts" / "local-project-names.txt"
CONFIG_FILE = REPO_ROOT / ".public-tree.toml"

# Matches this file's own "#   - <name>: ..." exclusion bullets so the
# excluded set has exactly one source of truth (the .txt file's own
# documented reasoning), rather than a second hardcoded list here that
# could silently drift from it.
EXCLUSION_BULLET_RE = re.compile(r"^#\s+- ([\w.\-]+):")


def read_names_and_exclusions() -> tuple[list[str], set[str]]:
    text = NAMES_FILE.read_text(encoding="utf-8")
    excluded: set[str] = set()
    names: list[str] = []
    for raw_line in text.splitlines():
        bullet = EXCLUSION_BULLET_RE.match(raw_line)
        if bullet:
            excluded.add(bullet.group(1))
            continue
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(line)
    return names, excluded


def existing_forbidden_lower(config_text: str) -> set[str]:
    """Lowercased literal payload of every current forbidden_strings entry
    (stripping a leading "(?i)" if present), so a name already covered --
    case-insensitively -- by a pre-existing entry (e.g. "yomu"/"infinitenote"
    are already covered by the floor's "(?i)Yomu"/"(?i)InfiniteNote") is
    never duplicated."""
    lines = config_text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("forbidden_strings = ["))
    covered = set()
    for line in lines[start + 1 :]:
        trimmed = line.strip()
        if trimmed == "]":
            break
        m = re.search(r'"(\(\?i\))?(.*)"', trimmed)
        if m:
            covered.add(m.group(2).lower())
    return covered


def build_synced_config(config_text: str) -> tuple[str, list[str]]:
    names, excluded = read_names_and_exclusions()
    covered = existing_forbidden_lower(config_text)

    to_add = []
    for name in names:
        if name in excluded:
            continue
        if name.lower() in covered:
            continue
        to_add.append(name)
        covered.add(name.lower())

    if not to_add:
        return config_text, []

    lines = config_text.splitlines(keepends=True)
    close_index = next(
        i
        for i in range(len(lines))
        if lines[i].startswith("forbidden_strings = [")
    )
    # Walk forward to the matching "]" line so new entries are inserted
    # immediately before it, after every existing entry.
    j = close_index + 1
    while lines[j].strip() != "]":
        j += 1

    # No escaping: every real name in local-project-names.txt today is a
    # plain identifier/slug (letters, digits, "-", "_") with no regex
    # metacharacters, matching the existing floor entries' own unescaped
    # style ("(?i)Yomu", not "(?i)Y\\o\\m\\u"). If a future name ever needs
    # a literal special character, escape it in the .txt file itself.
    new_lines = [f'  "(?i){name}",\n' for name in to_add]
    lines[j:j] = new_lines
    return "".join(lines), to_add


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    config_text = CONFIG_FILE.read_text(encoding="utf-8")
    synced_text, added = build_synced_config(config_text)

    if not added:
        print("forbidden_strings already in sync with Scripts/local-project-names.txt")
        return 0

    if check_only:
        print(
            "forbidden_strings is missing entries for: "
            + ", ".join(added)
            + " -- run Scripts/sync-local-project-name-forbidden-strings.py"
        )
        return 1

    CONFIG_FILE.write_text(synced_text, encoding="utf-8")
    print("Added to forbidden_strings: " + ", ".join(added))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
