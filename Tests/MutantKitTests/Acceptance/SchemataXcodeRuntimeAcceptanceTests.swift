import Testing

/// The end-to-end proof S3 exists to provide: a real `xcodebuild` build and
/// test run of a real `.xcodeproj`, linking the real
/// `MutantKitSchemataRuntimeC` through nothing but `xcodebuild` command-line
/// build-setting overrides (`OTHER_LDFLAGS`/`LIBRARY_SEARCH_PATHS`) — no
/// `.pbxproj` edit, no header, no module import. This is what
/// `BoolLiteralSchemataLowerer.runtimePreamble`'s switch to `@_silgen_name`
/// (instead of `import MutantKitSchemataRuntimeC`, S2's original approach)
/// exists to make possible: Xcode projects have no SwiftPM-style dependency
/// graph to hang an `import` on, but any linker can be told `-l<name>` from
/// the command line regardless.
///
/// The project itself is generated by `xcodegen` from a `project.yml`
/// written to a temp directory at test time — never committed to
/// `Fixtures/`, the same reason `SchemataSwiftPMRuntimeAcceptanceTests`
/// stages its package fresh rather than reusing a checked-in fixture: this
/// is proving the *injection mechanism*, not exercising the general
/// Xcode-project pipeline `AcceptanceSupport`'s existing fixtures already
/// cover. A macOS unit test target, not iOS Simulator, on purpose — it
/// isolates the linker-injection question from simulator-specific concerns
/// (code signing, device boot, dyld image loading inside a sandboxed
/// simulator) that ADR-0003 explicitly calls out as separate, harder,
/// still-open problems.
///
/// Off by default like every other acceptance suite (`xcodegen generate`
/// plus two real `xcodebuild` invocations): `MUTANTKIT_ACCEPTANCE=1 swift test`.
@Suite("Acceptance: Xcode schemata runtime", .enabled(if: Acceptance.isEnabled))
struct SchemataXcodeRuntimeAcceptanceTests {
    private static let fixtureSource = """
    public func isEnabled() -> Bool {
        true
    }

    """

    private static let testSource = """
    import XCTest
    import SchemataXcodeSpike

    final class WidgetTests: XCTestCase {
        func testIsEnabled() {
            XCTAssertTrue(isEnabled())
        }
    }

    """

    /// The real compilation unit `stageSpikeProject`'s `chunk`/`Widget.swift`
    /// lowers to — computed the same way `SchemataMutationRunner.runEntry`
    /// does in production; see `SchemataSwiftPMRuntimeAcceptanceTests`'s
    /// own identical fixture constant.
    private static let compilationUnitID = CompilationUnitID.derive(
        projectIdentity: "SchemataXcodeSpike.xcodeproj", target: "SchemataXcodeSpike", module: "SchemataXcodeSpike",
        sourcePath: "Widget.swift", lowererID: BoolLiteralSchemataLowerer.lowererID,
        lowererVersion: BoolLiteralSchemataLowerer.lowererVersion
    )

    /// Stages a throwaway macOS framework + unit-test-bundle Xcode project,
    /// generated by `xcodegen`, with the framework's one source file lowered
    /// by the real `BoolLiteralSchemataLowerer` — proving S1's output and
    /// S3's injection mechanism together.
    private struct StagedProject {
        let directory: URL
        let libraryDirectory: URL
        let token: SchemataSelectorToken
    }

    private func stageSpikeProject() throws -> StagedProject {
        let points = try CoreOperatorExpansionTestSupport.discover(
            Self.fixtureSource, operatorID: BoolLiteralInversionOperator.descriptor.id, relativePath: "Widget.swift"
        )
        let point = try #require(points.first, "expected one bool-literal candidate in the fixture")

        let chunk = SchemataChunk(
            chunkID: "xcode-spike-chunk", points: [point],
            projectIdentity: "SchemataXcodeSpike.xcodeproj",
            target: "SchemataXcodeSpike", module: "SchemataXcodeSpike", product: "SchemataXcodeSpike"
        )
        let program = try BoolLiteralSchemataLowerer().lower(
            chunk, sources: [SchemataSourceFile(relativePath: "Widget.swift", contents: Self.fixtureSource)]
        )
        let entry = try #require(program.entries.first)
        let token = try #require(entry.selectorToken)

        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("mutantkit-schemata-xcode-spike-\(UUID().uuidString)")
        let librarySourcesDirectory = directory.appendingPathComponent("Sources")
        let testSourcesDirectory = directory.appendingPathComponent("Tests")
        try FileManager.default.createDirectory(at: librarySourcesDirectory, withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: testSourcesDirectory, withIntermediateDirectories: true)

        let projectManifest = """
        name: SchemataXcodeSpike
        options:
          bundleIdPrefix: dev.mutantkit.spike
        targets:
          SchemataXcodeSpike:
            type: framework
            platform: macOS
            sources: [Sources]
            settings:
              base:
                GENERATE_INFOPLIST_FILE: YES
                # A distinctive, pre-existing linker flag — stands in for
                # whatever a real project's own target already needs linked.
                # `runtimeLinksAndActivatesViaBuildSettingOverridesOnly`
                # verifies the injected OTHER_LDFLAGS override does not
                # clobber this.
                OTHER_LDFLAGS: -framework Accelerate
          SchemataXcodeSpikeTests:
            type: bundle.unit-test
            platform: macOS
            sources: [Tests]
            dependencies:
              - target: SchemataXcodeSpike
                embed: true
            settings:
              base:
                GENERATE_INFOPLIST_FILE: YES
        schemes:
          SchemataXcodeSpike:
            build:
              targets:
                SchemataXcodeSpike: all
                SchemataXcodeSpikeTests: [test]
            test:
              targets: [SchemataXcodeSpikeTests]
        """
        try Data(projectManifest.utf8).write(to: directory.appendingPathComponent("project.yml"))
        // Every lowered source, not just Widget.swift — see the identical
        // fix in SchemataSwiftPMRuntimeAcceptanceTests.stageSpikePackage.
        for source in program.loweredSources {
            try Data(source.contents.utf8).write(to: librarySourcesDirectory.appendingPathComponent(source.relativePath))
        }
        try Data(Self.testSource.utf8).write(to: testSourcesDirectory.appendingPathComponent("WidgetTests.swift"))

        try runXcodegen(in: directory)
        let libraryDirectory = try runtimeLibraryDirectory()

        return StagedProject(directory: directory, libraryDirectory: libraryDirectory, token: token)
    }

    private func runXcodegen(in directory: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        process.arguments = ["xcodegen", "generate"]
        process.currentDirectoryURL = directory
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        try process.run()
        let output = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        process.waitUntilExit()
        #expect(process.terminationStatus == 0, "xcodegen generate failed:\n\(output)")
    }

    /// Locates the already-built `libMutantKitSchemataRuntime.a` — never
    /// shells out to `swift build` itself. `swift build --build-tests`
    /// (already run before every test invocation, the same prerequisite
    /// `AcceptanceSupport.binary()` relies on for the `mutantkit`
    /// executable) produces this as a side effect of `MutantKitTests`
    /// depending on the `MutantKitSchemataRuntimeC` target (see
    /// `Package.swift`) — invoking `swift build` again from *inside* an
    /// already-running `swift test` would deadlock on this package's own
    /// build lock, which is exactly what the first version of this suite
    /// did. `.build/debug` is SwiftPM's own convenience symlink to the
    /// current platform triple's debug directory, so this needs no
    /// hardcoded architecture.
    private func runtimeLibraryDirectory() throws -> URL {
        let directory = Acceptance.packageRoot.appendingPathComponent(".build/debug")
        let library = directory.appendingPathComponent("libMutantKitSchemataRuntime.a")
        guard FileManager.default.fileExists(atPath: library.path) else {
            throw AcceptanceError.binaryMissing(library.path)
        }
        return directory
    }

    /// Runs the project's test scheme once, with `environment` merged over
    /// this process's own, and the runtime linked in via build-setting
    /// overrides only — no `.pbxproj` touched — and produces the
    /// `.xctestrun` `runXCTestRun(_:environment:)` then re-runs twice with
    /// different environments. A codex-review-caliber finding from this
    /// suite's own first draft: setting `Process.environment` on the
    /// `xcodebuild` invocation itself does *not* reliably reach the actual
    /// `xctest` process Xcode's own tooling launches — env vars must be
    /// injected into the `.xctestrun` plist's `EnvironmentVariables`
    /// dictionary instead, the same mechanism a scheme's own "Environment
    /// Variables" editor pane ultimately writes to.
    private func buildForTesting(directory: URL, libraryDirectory: URL) throws -> URL {
        let derivedDataPath = directory.appendingPathComponent("DerivedData")
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
        process.arguments = [
            "xcodebuild", "build-for-testing",
            "-scheme", "SchemataXcodeSpike",
            "-destination", "platform=macOS",
            "-derivedDataPath", derivedDataPath.path,
            "OTHER_LDFLAGS=$(inherited) -lMutantKitSchemataRuntime",
            "LIBRARY_SEARCH_PATHS=$(inherited) \(libraryDirectory.path)"
        ]
        process.currentDirectoryURL = directory
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        try process.run()
        let output = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        process.waitUntilExit()
        #expect(process.terminationStatus == 0, "xcodebuild build-for-testing failed:\n\(output)")

        let enumerator = FileManager.default.enumerator(at: derivedDataPath, includingPropertiesForKeys: nil)
        let xctestrun = enumerator?.compactMap { $0 as? URL }.first { $0.pathExtension == "xctestrun" }
        return try #require(xctestrun, "no .xctestrun produced under \(derivedDataPath.path)")
    }

    /// Confirms the *actual built binary* links both the project's own
    /// pre-existing dependency (`Accelerate.framework`, standing in for
    /// whatever a real project's target already needs) and the injected
    /// runtime symbol — proof `$(inherited)` actually preserved the former
    /// rather than the override silently replacing it. Inspects the linked-
    /// library list directly (`otool -L`) rather than asking `xcodebuild
    /// -showBuildSettings` to resolve `$(inherited)` for us: that command
    /// echoes a command-line-supplied `OTHER_LDFLAGS` override back
    /// verbatim rather than expanding it, so it cannot actually answer this
    /// question — only the binary the build produced can.
    private func builtFrameworkLinksAccelerate(directory: URL) throws -> Bool {
        let derivedDataPath = directory.appendingPathComponent("DerivedData")
        let binary = derivedDataPath
            .appendingPathComponent("Build/Products/Debug/SchemataXcodeSpike.framework/Versions/A/SchemataXcodeSpike")
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/otool")
        process.arguments = ["-L", binary.path]
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        try process.run()
        let output = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        process.waitUntilExit()
        #expect(process.terminationStatus == 0, "otool -L failed on \(binary.path):\n\(output)")
        return output.contains("Accelerate.framework")
    }

    /// Writes a copy of the base `.xctestrun` with `environment` merged
    /// into every test target's own `EnvironmentVariables` dictionary
    /// (creating it if the base plist has none), and runs it via
    /// `test-without-building` — reusing the one build both calls share
    /// rather than rebuilding per environment, the same efficiency
    /// `SchemataSwiftPMRuntimeAcceptanceTests` gets from building its
    /// package once and running the binary twice.
    private func runXCTestRun(
        _ baseXCTestRun: URL, environment: [String: String]
    ) throws -> (testsPassed: Bool, output: String) {
        var plist = try #require(
            NSDictionary(contentsOf: baseXCTestRun) as? [String: Any], "malformed .xctestrun at \(baseXCTestRun.path)"
        )
        for key in plist.keys where key != "__xctestrun_metadata__" {
            guard var target = plist[key] as? [String: Any] else { continue }
            var targetEnvironment = target["EnvironmentVariables"] as? [String: String] ?? [:]
            for (variable, value) in environment { targetEnvironment[variable] = value }
            target["EnvironmentVariables"] = targetEnvironment
            plist[key] = target
        }

        let variant = baseXCTestRun.deletingLastPathComponent()
            .appendingPathComponent("variant-\(UUID().uuidString).xctestrun")
        try (plist as NSDictionary).write(to: variant, atomically: true)

        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
        process.arguments = ["xcodebuild", "test-without-building", "-xctestrun", variant.path, "-destination", "platform=macOS"]
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        try process.run()
        let output = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        process.waitUntilExit()
        return (process.terminationStatus == 0, output)
    }

    @Test("The runtime links via build-setting overrides alone, and the mutation activates only with the requested token")
    func runtimeLinksAndActivatesViaBuildSettingOverridesOnly() throws {
        let staged = try stageSpikeProject()
        defer { try? FileManager.default.removeItem(at: staged.directory) }

        let baseXCTestRun = try buildForTesting(directory: staged.directory, libraryDirectory: staged.libraryDirectory)

        // The build already succeeded (`buildForTesting` asserted that) —
        // this additionally proves `$(inherited)` actually preserved the
        // project's own pre-existing linker flag rather than the injected
        // override silently replacing it, which a merely-successful build
        // would not rule out on its own (nothing in this fixture's code
        // actually calls an Accelerate symbol, so dropping the flag
        // wouldn't itself cause a link error).
        #expect(
            try builtFrameworkLinksAccelerate(directory: staged.directory),
            "the project's own pre-existing OTHER_LDFLAGS must survive the injected override"
        )

        let unmutated = try runXCTestRun(baseXCTestRun, environment: [:])
        #expect(unmutated.testsPassed, "no requested token must behave exactly like the original program:\n\(unmutated.output)")

        // The point this test exists to prove: the host here never learns
        // the actual `xctest` process's PID in advance — `xcodebuild`
        // launches it as an unobserved descendant, unlike the SwiftPM path,
        // which gets `Process.processIdentifier` directly. It doesn't need
        // to: the real transcript reports the PID itself, from a startup
        // event matched by the run ID this host *does* control.
        let transcriptPath = FileManager.default.temporaryDirectory.appendingPathComponent("transcript-\(UUID().uuidString).bin")
        defer { try? FileManager.default.removeItem(at: transcriptPath) }
        let runID = RunID()

        let mutated = try runXCTestRun(baseXCTestRun, environment: [
            SchemataEvidenceCollector.tokenEnvironmentVariable: SchemataEvidenceCollector.tokenEnvironmentValue(for: staged.token),
            SchemataEvidenceCollector.transcriptPathEnvironmentVariable: transcriptPath.path,
            SchemataEvidenceCollector.runIDEnvironmentVariable: SchemataEvidenceCollector.runIDEnvironmentValue(for: runID)
        ])
        #expect(!mutated.testsPassed, "the requested token must activate the embedded mutation and flip the test's result:\n\(mutated.output)")

        let transcript = try SchemataEvidenceCollector.readTranscript(at: transcriptPath)
        let startup = try #require(transcript.records.compactMap { record -> RuntimeStartupEvent? in
            guard case let .startup(event) = record, event.token == staged.token, event.runID == runID else { return nil }
            return event
        }.first, "a real xctest process, whose PID this host never predicted, must still leave a startup event")
        #expect(startup.compilationUnitID == Self.compilationUnitID)
        let hit = try #require(transcript.records.compactMap { record -> RuntimeHitEvent? in
            guard case let .hit(event) = record, event.token == staged.token, event.runID == startup.runID, event.processID == startup.processID
            else { return nil }
            return event
        }.first, "and a hit from that same process")
        #expect(hit.compilationUnitID == Self.compilationUnitID)
    }
}
