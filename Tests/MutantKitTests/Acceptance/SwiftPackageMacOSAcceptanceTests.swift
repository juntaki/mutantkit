import Foundation
import MutationModel
import Testing

/// The whole pipeline against a real Swift package: plan, sandbox, apply, build,
/// test, classify, prove, report.
///
/// The assertions name the exact mutations expected to live and die rather than
/// checking a score. A score is a single number that many different — and many
/// wrong — runs can produce: the run that mutated nothing and the run that mutated
/// everything correctly can agree on 42.86%. Naming the mutants is what makes the
/// fixture's deliberate calibration mean something, and what would have caught the
/// build reading unmutated sources while every count still looked plausible.
@Suite("Acceptance: Swift package on macOS", .enabled(if: Acceptance.isEnabled))
struct SwiftPackageMacOSAcceptanceTests {
    /// Pinned rather than generated by `init`, so a change to the `init` template
    /// cannot silently change what this suite tests.
    private static let configuration = """
    version: 1
    project:
      kind: swiftPackageMacOS
    sources:
      include: [Sources/**]
    operators:
      profile: default
    execution:
      strategy: isolated
      workers: 2
    reports: [console, json]
    """

    /// One run, shared by every assertion about it.
    ///
    /// Swift Testing builds a fresh suite instance per test, so a per-test run
    /// would rebuild and re-test the whole package once per assertion — four full
    /// pipelines to inspect one result, which measured at seven minutes. The run
    /// is a read-only artifact, so sharing it costs nothing but the loss of
    /// per-test isolation, and there is nothing here to isolate: the tests only
    /// read it.
    ///
    /// Safe to share: `static let` initializes under `swift_once`, so concurrent
    /// tests cannot race it. `Result` is what carries a planning failure into
    /// whichever test observes it first, rather than trapping during
    /// initialization with no attribution.
    private static let sharedRun = Result {
        try Acceptance.planAndRun(fixture: "SwiftPackageMacOS", configuration: configuration)
    }

    private func run() throws -> AcceptanceRun {
        try Self.sharedRun.get()
    }

    @Test("The run reconciles and produces a score")
    func runIsInternallyConsistent() throws {
        let run = try self.run()

        #expect(run.report.baseline.passed)
        #expect(run.report.baseline.testSummary?.total == 4)

        let integrity = run.report.integrity
        #expect(integrity.violations.isEmpty, "\(integrity.violations.map(\.detail))")
        #expect(integrity.discovered == 7)
        #expect(integrity.planned == 7)
        // Every planned mutation reached the source, the compiler and a verdict.
        #expect(integrity.sourceApplied == 7)
        #expect(integrity.buildObserved == 7)
        #expect(integrity.classified == 7)
        #expect(integrity.reported == 7)

        #expect(run.report.score != nil)
        #expect(run.exitCode == 0)
    }

    /// `qualifiesForSeniorRate` is tested at 64, 65 and 66, so nothing about `>=`
    /// survives. `bulkDiscountRate` is tested at 3 and 50 — inside each branch,
    /// never at the boundary — so reversing it dies while shifting it lives. That
    /// asymmetry is the entire point of the fixture, and of mutation testing.
    @Test("Exactly the uncovered mutations survive")
    func survivorsAreExactlyTheUncoveredOnes() throws {
        let run = try self.run()

        #expect(run.mutations(withOutcome: .survived) == [
            // The default is never exercised: both tests pass the flag explicitly.
            .init(declaration: "init(loyaltyDiscountEnabled:)", original: "true", replacement: "false"),
            // The off-by-one this suite cannot see.
            .init(declaration: "bulkDiscountRate(itemCount:)", original: ">", replacement: ">="),
            // Untested outright.
            .init(declaration: "isFreeShipping(total:)", original: ">=", replacement: ">"),
            .init(declaration: "isFreeShipping(total:)", original: ">=", replacement: "<")
        ])

        #expect(run.killed == [
            .init(declaration: "qualifiesForSeniorRate(age:)", original: ">=", replacement: ">"),
            .init(declaration: "qualifiesForSeniorRate(age:)", original: ">=", replacement: "<"),
            .init(declaration: "bulkDiscountRate(itemCount:)", original: ">", replacement: "<=")
        ])
    }

    /// The product's central promise, checked against a real run rather than a
    /// constructed report.
    @Test("Every reported mutant carries evidence that it reached the source")
    func everyMutantHasASourceDiff() throws {
        let run = try self.run()

        for result in run.report.results {
            let evidence = try #require(result.evidence, "\(result.point.displayLocation) has no evidence")
            #expect(evidence.provesSourceApplication, "\(result.point.displayLocation)")
            #expect(evidence.sourceBeforeHash != evidence.sourceAfterHash)
            #expect(evidence.sourceDiff.contains("--- a/Sources/Pricing/Pricing.swift"))
            // The diff is the artifact a developer acts on, so it must actually
            // show the change rather than merely exist.
            #expect(evidence.sourceDiff.contains("+\(result.point.replacementText)")
                || evidence.sourceDiff.contains(result.point.replacementText))
        }
    }

    /// Activation evidence is only meaningful if it can distinguish anything. A
    /// mutant proven active is a claim about the binary, not about the file.
    @Test("Every scored mutant is proven active in the build product")
    func everyScoredMutantIsProvenActive() throws {
        let run = try self.run()

        for result in run.report.results where result.outcome.isScorable {
            let activation = try #require(
                result.evidence?.applicationEvidence?.isolatedActivation,
                "\(result.point.displayLocation) was scored without activation evidence"
            )
            #expect(activation.provesActivation, "\(result.point.displayLocation)")
        }
    }

    /// Determinism is a headline claim, and the cheapest way for it to be false is
    /// for discovery to depend on file completion order.
    @Test("Planning twice produces byte-identical plans")
    func planningIsDeterministic() throws {
        let directory = try Acceptance.stageFixture("SwiftPackageMacOS")
        defer { try? FileManager.default.removeItem(at: directory) }
        try Data(Self.configuration.utf8)
            .write(to: directory.appendingPathComponent("mutantkit.yml"), options: .atomic)

        try Acceptance.run(["plan", "--output", "a.json"], in: directory)
        try Acceptance.run(["plan", "--output", "b.json"], in: directory)

        let a = try MutationPlan.decode(from: Data(contentsOf: directory.appendingPathComponent("a.json")))
        let b = try MutationPlan.decode(from: Data(contentsOf: directory.appendingPathComponent("b.json")))

        #expect(a.planID == b.planID)
        #expect(a.mutations.map(\.id) == b.mutations.map(\.id))
    }

    /// "Hash differs → activated" only means something if "hash differs" never
    /// happens on its own. Three independent sandboxes, same unmutated source,
    /// same configuration — if the toolchain embedded anything sandbox-specific
    /// (a timestamp, an absolute path of different length, a UUID unrelated to
    /// code), this is where it would show up as a false "activated" on every
    /// mutant, silently, since a real mutation always changes the hash too and
    /// the two causes are indistinguishable from a single run.
    @Test("Building the same source three times in separate sandboxes yields the same hash")
    func baselineHashIsRepeatableAcrossSandboxes() throws {
        let hashes = try (0 ..< 3).map { _ -> String in
            let run = try Acceptance.planAndRun(fixture: "SwiftPackageMacOS", configuration: Self.configuration)
            defer { run.cleanUp() }
            return try #require(run.report.baseline.buildProductHash, "baseline hash missing")
        }
        #expect(Set(hashes).count == 1, "\(hashes)")
    }

    /// `verify` is the cheap pre-flight that catches a stale plan before an hour of
    /// builds, so it has to actually pass on a fresh one.
    @Test("A fresh plan verifies, and a mutated tree invalidates it")
    func verifyDetectsAStalePlan() throws {
        let directory = try Acceptance.stageFixture("SwiftPackageMacOS")
        defer { try? FileManager.default.removeItem(at: directory) }
        try Data(Self.configuration.utf8)
            .write(to: directory.appendingPathComponent("mutantkit.yml"), options: .atomic)

        try Acceptance.run(["plan", "--output", "plan.json"], in: directory)
        #expect(try Acceptance.run(["verify", "--plan", "plan.json"], in: directory).exitCode == 0)

        // Editing the source must invalidate the anchors rather than silently
        // relocating them.
        let source = directory.appendingPathComponent("Sources/Pricing/Pricing.swift")
        let edited = try String(contentsOf: source, encoding: .utf8)
            .replacingOccurrences(of: "import Foundation", with: "import Foundation\n// a new line")
        try Data(edited.utf8).write(to: source, options: .atomic)

        let stale = try Acceptance.run(["verify", "--plan", "plan.json"], in: directory)
        #expect(stale.exitCode != 0)
        #expect(stale.output.contains("changed since planning"))
    }
}
